# System instruction: role, structure and the "no invented numbers" rule.
SYSTEM_INSTRUCTION = """You are a senior data analyst writing for Mamaearth's regional ops and finance heads.

Write a business narrative of about 250 words with exactly three labeled sections:
Situation, Complication, Resolution.

Rules:
- Use ONLY the numbers in the supplied findings.
- Every number you write must have exactly the same value as in the findings.
- Do not invent any statistic, percentage, date or comparison that is not in the findings."""

# User prompt: built from the findings argument (nothing is hardcoded).
def build_prompt(findings):
    return (
        "Write the Situation, Complication and Resolution narrative "
        "using these verified findings:\n\n"
        + json.dumps(findings, indent=2)
    )


# Show the prompt that is created from our findings.
print(build_prompt(findings))

"""### Observation

The role, the three sections and the "no invented numbers" rule are kept in the **system instruction**, separate from the user prompt. The user prompt only carries the data, and it is created from the `findings` argument with `json.dumps`. If `findings.json` changes, the prompt changes automatically.

## Task 3: Gemini call with parameter locking and error handling

Call Gemini with these locked settings:

- `temperature=0.0`: this is a factual business report, so the answer should be as predictable as possible.
- `max_output_tokens=1024`: an explicit value (at least 300) with enough space for a three-section narrative.
- `timeout`: 30 seconds (the minimum allowed is 10).

The whole call is inside `try/except`, so the caller always gets a dictionary and never a raw error.
"""

def generate_scr_narrative_gemini(findings, api_key):
    """Ask Gemini for the SCR narrative. Always returns a dictionary."""
    try:
        # The imports are inside try, so a missing library also returns an error dictionary.
        from google import genai
        from google.genai import types

        # Timeout is given in milliseconds: 30000 ms = 30 seconds.
        client = genai.Client(api_key=api_key, http_options=types.HttpOptions(timeout=30000))

        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=build_prompt(findings),             # user prompt (Task 2)
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_INSTRUCTION,   # system instruction (Task 2)
                temperature=0.0,        # factual report, not creative writing
                max_output_tokens=1024, # explicit limit, enough for ~250 words
                thinking_config=types.ThinkingConfig(thinking_budget=0),  # no hidden "thinking" tokens
            ),
        )

        return {
            "status": "success",
            "narrative": response.text,
            "tokens": response.usage_metadata.total_token_count,
        }

    except Exception as err:
        # Never raise: return the problem in a dictionary.
        return {"status": "error", "narrative": None, "message": str(err)}

# Demo of the error branch: a wrong key must give an error dictionary, not a crash.
