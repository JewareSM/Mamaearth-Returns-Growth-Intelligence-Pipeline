"""### Observation

The yellow marks appear **only in two columns: `discount_pct` and `rating`**. All other columns are completely filled (purple). Ratings have more gaps than discounts, which matches the counts printed in the next cell (15 vs 12).
"""

# Count the missing values BEFORE filling them.
missing_discount = int(orders_clean['discount_pct'].isnull().sum())
missing_rating = int(orders_clean['rating'].isnull().sum())
print("Missing before imputation:", {'discount_pct': missing_discount, 'rating': missing_rating})

# Median of the ratings that exist (printed BEFORE filling, expected 3.0).
median_rating = orders_clean['rating'].median()
print("Median rating before imputation:", median_rating)

# Fill missing discounts with 0 and missing ratings with the median.
orders_clean['discount_pct'] = orders_clean['discount_pct'].fillna(0)
orders_clean['rating'] = orders_clean['rating'].fillna(median_rating)
print("Rows filled -> discount_pct:", missing_discount, "| rating:", missing_rating)

# Check that nothing is missing now.
print("Missing after imputation:", orders_clean[['discount_pct', 'rating']].isnull().sum().to_dict())

"""### Observation

**12 discounts** and **15 ratings** were missing. Missing discounts were set to 0 (no promo applied) and missing ratings to the median rating, **3.0**. After filling, both columns have **0 missing values**. The median is a safe choice because it is not pulled by very high or very low ratings.

### Task 4b: Heatmap of missing values (after imputation)

The same heatmap again, to **prove** that the missing values were filled.
"""

# Heatmap of missing values AFTER filling them.
