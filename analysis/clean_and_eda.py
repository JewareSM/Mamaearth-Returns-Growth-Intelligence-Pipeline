"""### Observation

Exactly **5 duplicate orders** were found and dropped: **O0176, O0177, O0178, O0179 and O0180**. They are copies of earlier orders, so they would have been counted twice. The cleaned table now has **175 rows**. Duplicates are removed *before* imputing, so the missing-value counts in the next task are counted on the 175 rows.

## Task 4: Impute missing values

Fill missing `discount_pct` with **0** (no promo code was used) and missing `rating` with the **median** of the existing ratings.

### Task 4a: Heatmap of missing values (before imputation)

A heatmap shows every cell of the table as a small box: **yellow = missing value**, **purple = value present**. Each row is one order and each column is one field.
"""

# Heatmap of missing values BEFORE filling them (True = missing).
plt.figure(figsize=(9, 5))
