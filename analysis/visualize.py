"""## Step 2: Load the data

Load the three CSV files into the DataFrames `customers`, `products` and `orders` (same code as in `clean_and_eda.ipynb`).
"""

import pandas as pd
import matplotlib.pyplot as plt

# Load Customers, Products, and Orders CSV files into separate DataFrames

customers = pd.read_csv('/content/drive/MyDrive/IITR_Capstone_Project/customers.csv')
products = pd.read_csv('/content/drive/MyDrive/IITR_Capstone_Project/products.csv')
orders = pd.read_csv('/content/drive/MyDrive/IITR_Capstone_Project/orders.csv')

# Check the shape (rows, columns) of each table.
print("customers.shape:", customers.shape)   # expected (45, 6)
print("products.shape :", products.shape)    # expected (16, 4)
print("orders.shape   :", orders.shape)      # expected (180, 9)

"""## Step 3: Clean the orders (Tasks 2, 3 and 4)

Same cleaning as in `clean_and_eda.ipynb`: standardize the payment method, remove the duplicate orders and fill the missing values.
"""

# 1) Standardize payment_method: remove spaces and convert to uppercase (7 spellings become 3).
orders['payment_method'] = orders['payment_method'].str.strip().str.upper()

# 2) Remove duplicate orders (identical in every column except order_id).
duplicate_columns = ['customer_id', 'product_id', 'order_date', 'quantity',
                     'discount_pct', 'payment_method', 'rating', 'returned']
orders_clean = orders.drop_duplicates(subset=duplicate_columns, keep='first').copy()

# 3) Fill missing values: discount with 0, rating with the median rating.
median_rating = orders_clean['rating'].median()
orders_clean['discount_pct'] = orders_clean['discount_pct'].fillna(0)
orders_clean['rating'] = orders_clean['rating'].fillna(median_rating)

# Checks.
print("Payment methods:", orders_clean['payment_method'].unique().tolist())
print("orders_clean.shape:", orders_clean.shape)    # expected (175, 9)
print("Median rating used:", median_rating)         # expected 3.0
print("Missing values left:", orders_clean[['discount_pct', 'rating']].isnull().sum().to_dict())

"""## Step 4: Merge the tables and flag outliers (Tasks 5 and 6)

Join the orders with products and customers, calculate `order_value`, and flag the quantity outliers with the IQR rule. The outliers are flagged, not dropped.
"""

# Merge orders with products (product_id), then with customers (customer_id).
merged_data = orders_clean.merge(products, on='product_id', how='left')
merged_data = merged_data.merge(customers, on='customer_id', how='left')

# Value of each order after the discount.
merged_data['order_value'] = (
    merged_data['quantity'] * merged_data['price'] *
    (1 - merged_data['discount_pct'] / 100)
)

# Flag quantity outliers with the IQR rule.
q1 = merged_data['quantity'].quantile(0.25)
q3 = merged_data['quantity'].quantile(0.75)
iqr = q3 - q1
lower_limit = q1 - 1.5 * iqr
upper_limit = q3 + 1.5 * iqr
merged_data['is_outlier'] = (
    (merged_data['quantity'] < lower_limit) | (merged_data['quantity'] > upper_limit)
)

# Checks.
print(f"Cleaned total order_value: {merged_data['order_value'].sum():.2f}")   # expected 97358.30
print("Outlier limits:", lower_limit, "to", upper_limit)                       # expected -0.5 to 3.5
print("Outlier orders:", merged_data.loc[merged_data['is_outlier'], 'order_id'].tolist())

"""## Step 5: Prepare the data for the charts (Tasks 7 and 10)

Calculate the return rate for each payment method (Chart 1) and the outlier-corrected monthly revenue (Chart 2).
"""

# Chart 1 data: return rate (%) for each payment method.
payment_analysis = merged_data.groupby('payment_method')['returned'].agg(['count', 'mean'])
payment_analysis['return_rate'] = (payment_analysis['mean'] * 100).round(1)

# Sorted from highest to lowest.
return_rates_sorted = payment_analysis['return_rate'].sort_values(ascending=False)
print("Return rate by payment method (%):")
print(return_rates_sorted.to_string())

# Chart 2 data: monthly revenue EXCLUDING the outlier orders.
merged_data['order_date'] = pd.to_datetime(merged_data['order_date'])
merged_data['month'] = merged_data['order_date'].dt.to_period('M')
corrected_revenue = merged_data[~merged_data['is_outlier']].groupby('month')['order_value'].sum().round(2)
corrected_peak_month = corrected_revenue.idxmax()

print("\nCorrected monthly revenue (INR):")
for month, value in corrected_revenue.items():
    print(f"  {month}: {value:.2f}")
print("\nTrue peak month:", corrected_peak_month)

"""## Step 6: Chart 1 - Return rate by payment method

A bar chart of the return rate for each cleaned payment method, **highest first**, with the exact percentage written on each bar. The title states the finding and is built from the numbers, not typed by hand.
"""

# Return rates sorted from highest to lowest (prepared in Step 5).
rates = return_rates_sorted

highest_method = rates.index[0]       # payment method with the highest rate
highest_rate = rates.iloc[0]          # its return rate
lowest_method = rates.index[-1]       # payment method with the lowest rate
lowest_rate = rates.iloc[-1]          # its return rate

# How many times higher is the highest rate than the lowest rate?
times_higher = highest_rate / lowest_rate

# Draw the bar chart.
fig, ax = plt.subplots(figsize=(7, 5))
bars = ax.bar(rates.index, rates.values, color=["#c0392b", "#2980b9", "#7f8c8d"])

# Write the exact percentage on top of each bar.
for bar, rate in zip(bars, rates.values):
    ax.text(bar.get_x() + bar.get_width() / 2, rate + 0.8, f"{rate:.1f}%",
            ha="center", fontweight="bold")

# The title states the finding.
ax.set_title(f"{highest_method} Returns at {highest_rate:.1f}% - "
             f"{times_higher:.0f}x {lowest_method.title()}")
ax.set_xlabel("Payment method")
ax.set_ylabel("Return rate (%)")
ax.set_ylim(0, highest_rate * 1.15)   # leave space above the tallest bar

plt.tight_layout()
plt.show()

"""### Observation

**COD returns at 44.4%**, about **3 times the rate of CARD (14.7%)** and about 2.3 times UPI (18.9%). The bars are in descending order, so the problem payment method is visible at a glance. This supports the hypothesis from Task 7.

## Step 7: Chart 2 - Outlier-corrected monthly revenue

A line chart of monthly revenue **after excluding the two bulk orders** (not the inflated version), with labelled axes and a title that names the real peak month.
"""

# Month labels (for example "2026-01") and the corrected revenue values.
months = [str(m) for m in corrected_revenue.index]
revenue = corrected_revenue.values

# The real peak month and its revenue (from Task 10).
peak_month = corrected_peak_month
peak_revenue = corrected_revenue[peak_month]
peak_label = peak_month.strftime("%B %Y")        # for example "March 2026"

# Draw the line chart.
fig, ax = plt.subplots(figsize=(8, 5))
ax.plot(months, revenue, marker="o", linewidth=2)

# Write the revenue value above the peak point.
ax.annotate(f"{peak_revenue:,.0f}", xy=(str(peak_month), peak_revenue),
            xytext=(0, 10), textcoords="offset points",
            ha="center", fontweight="bold")

ax.set_title(f"Outlier-Corrected Monthly Revenue - Peak in {peak_label}")
ax.set_xlabel("Month")
ax.set_ylabel("Revenue (INR)")
ax.set_ylim(0, peak_revenue * 1.15)
ax.grid(axis="y", alpha=0.3)

plt.tight_layout()
plt.show()

"""### Observation

After removing the two bulk orders, **March 2026 is the clear peak** at about **INR 20,319**. January is no longer a spike (about INR 11,637), and April is the weakest month (about INR 9,495). The earlier "January peak" was only caused by the outlier orders O0011 and O0098.
"""